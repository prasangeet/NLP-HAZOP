"""E7: robustness of HAZOP relationship recovery under evidence masking.

This experiment keeps the scenario-level train/test split fixed and randomly
removes typed relationships from the TRAINING evidence at several rates.
For each masking seed, masks are nested: the 10% mask is a subset of the 20%
mask, etc. Test labels are never modified.

The benchmark evaluates the deterministic methods already implemented in
scripts.run_benchmark:
  - TF-IDF vector retrieval
  - typed graph reasoning
  - graph + TF-IDF candidate union

Run from the server directory:
    uv run python -m scripts.run_experiment_7

No Gemini calls are made.
"""

from __future__ import annotations

import argparse
import json
import logging
import random
import statistics
from collections import defaultdict
from dataclasses import replace
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from scripts import run_benchmark as benchmark

logger = logging.getLogger("experiment_7")

DEFAULT_MASK_RATES = (0.10, 0.20, 0.30, 0.40)
DEFAULT_MASK_SEEDS = tuple(range(42, 52))
METRICS = (
    "micro_precision",
    "micro_recall",
    "micro_f1",
    "macro_f1",
    "coverage",
    "abstention_rate",
    "mean_candidates",
    "mrr",
    "mean_latency_ms",
)

# These predicates are generated by HazopCsvLoader. The projection below
# keeps the record's searchable endpoint fields consistent with the surviving
# typed relationships. This matters because TF-IDF reads the record fields,
# while graph reasoning reads causal_relations.
CAUSE_PREDICATE = "causes_deviation"
EFFECT_PREDICATE = "leads_to"
CONSEQUENCE_PREDICATES = {
    "leads_to_consequence",
    "co_occurs_with_consequence",
}


def _unique_in_order(values: list[str]) -> tuple[str, ...]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        key = value.casefold().strip()
        if key and key not in seen:
            seen.add(key)
            result.append(value.strip())
    return tuple(result)


def _project_record_from_relations(record, relations):
    """Return a record whose searchable endpoints reflect surviving edges."""
    causes = _unique_in_order(
        [
            relation.subject
            for relation in relations
            if relation.predicate.casefold() == CAUSE_PREDICATE
        ]
    )
    effects = _unique_in_order(
        [
            relation.object
            for relation in relations
            if relation.predicate.casefold() == EFFECT_PREDICATE
        ]
    )
    consequences = _unique_in_order(
        [
            relation.object
            for relation in relations
            if relation.predicate.casefold() in CONSEQUENCE_PREDICATES
        ]
    )
    return replace(
        record,
        causes=causes,
        effects=effects,
        consequences=consequences,
        causal_relations=tuple(relations),
    )


def mask_training_relationships(
    training_records,
    *,
    mask_rate: float,
    seed: int,
):
    """Mask a reproducible global fraction of typed training relationships.

    The same shuffled edge order is used at every rate for a given seed, so
    higher-rate masks contain all edges removed at lower rates.
    """
    if not 0.0 <= mask_rate < 1.0:
        raise ValueError("mask_rate must be in [0, 1)")

    edge_refs = [
        (record_index, edge_index)
        for record_index, record in enumerate(training_records)
        for edge_index, _ in enumerate(record.causal_relations)
    ]
    if not edge_refs:
        raise ValueError("Training split contains no typed relationships to mask.")

    shuffled_refs = list(edge_refs)
    random.Random(seed).shuffle(shuffled_refs)
    n_remove = round(len(edge_refs) * mask_rate)
    removed_refs = set(shuffled_refs[:n_remove])

    masked_records = []
    removed_by_record: dict[str, int] = defaultdict(int)
    retained_by_record: dict[str, int] = defaultdict(int)
    removed_by_predicate: dict[str, int] = defaultdict(int)
    retained_by_predicate: dict[str, int] = defaultdict(int)

    for record_index, record in enumerate(training_records):
        kept_relations = []
        for edge_index, relation in enumerate(record.causal_relations):
            predicate = relation.predicate.casefold()
            if (record_index, edge_index) in removed_refs:
                removed_by_record[record.scenario_id] += 1
                removed_by_predicate[predicate] += 1
            else:
                kept_relations.append(relation)
                retained_by_record[record.scenario_id] += 1
                retained_by_predicate[predicate] += 1

        masked_records.append(
            _project_record_from_relations(record, kept_relations)
        )

    return {
        "records": tuple(masked_records),
        "total_relationships": len(edge_refs),
        "removed_relationships": n_remove,
        "retained_relationships": len(edge_refs) - n_remove,
        "actual_mask_rate": n_remove / len(edge_refs),
        "removed_by_scenario": dict(sorted(removed_by_record.items())),
        "retained_by_scenario": dict(sorted(retained_by_record.items())),
        "removed_by_predicate": dict(sorted(removed_by_predicate.items())),
        "retained_by_predicate": dict(sorted(retained_by_predicate.items())),
    }


def _compact_case_results(cases: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Keep per-query outputs auditable without duplicating verbose evidence."""
    compact = []
    for case in cases:
        method_results = {}
        for method_name, method in case.get("methods", {}).items():
            method_results[method_name] = {
                "status": method.get("status"),
                "latency_ms": method.get("latency_ms", 0.0),
                "predictions": [
                    prediction.get("value")
                    for prediction in method.get("predictions", [])
                    if prediction.get("value")
                ],
            }
        compact.append(
            {
                "case_id": case["case_id"],
                "scenario_id": case["scenario_id"],
                "known_endpoint": case["known_endpoint"],
                "gold_values": case["gold_values"],
                "methods": method_results,
            }
        )
    return compact


def _aggregate_runs(runs: list[dict[str, Any]]) -> dict[str, Any]:
    grouped: dict[tuple[float, str], list[dict[str, Any]]] = defaultdict(list)
    for run in runs:
        rate = float(run["mask_rate"])
        for method, summary in run["method_summary"].items():
            if summary.get("status") != "evaluated":
                continue
            grouped[(rate, method)].append(summary)

    aggregate: dict[str, Any] = {}
    for (rate, method), summaries in sorted(grouped.items()):
        metric_summary = {}
        for metric in METRICS:
            values = [
                float(summary[metric])
                for summary in summaries
                if summary.get(metric) is not None
            ]
            if not values:
                continue
            metric_summary[metric] = {
                "mean": statistics.mean(values),
                "std": statistics.stdev(values) if len(values) > 1 else 0.0,
                "min": min(values),
                "max": max(values),
            }
        aggregate.setdefault(f"{rate:.2f}", {})[method] = {
            "n_runs": len(summaries),
            "metrics": metric_summary,
        }
    return aggregate


def run_experiment(args: argparse.Namespace) -> dict[str, Any]:
    dataset_path = Path(args.dataset_path).resolve() if args.dataset_path else None
    original_records = benchmark.load_dataset(args.dataset, dataset_path)

    # Holdout membership is fixed across every masking seed and rate. Only
    # training evidence changes; all held-out labels remain untouched.
    train, test = benchmark.stable_split(
        original_records,
        test_fraction=args.test_fraction,
        seed=args.split_seed,
    )
    if not train or not test:
        raise ValueError("The fixed scenario split produced an empty partition.")

    original_training_edges = sum(
        len(record.causal_relations) for record in train
    )
    if original_training_edges == 0:
        raise ValueError("No typed relationships found in the training split.")

    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    runs_path = output_dir / "e7_runs.jsonl"
    summary_path = output_dir / "e7_summary.json"

    # Refuse to append to a previous run: every execution gets a unique file.
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    runs_path = output_dir / f"e7_runs_{stamp}.jsonl"
    summary_path = output_dir / f"e7_summary_{stamp}.json"

    logger.info(
        "E7 starting | dataset=%s records=%d train=%d test=%d "
        "train_relationships=%d rates=%s seeds=%s",
        args.dataset,
        len(original_records),
        len(train),
        len(test),
        original_training_edges,
        args.mask_rates,
        args.mask_seeds,
    )

    run_records: list[dict[str, Any]] = []
    total_runs = len(args.mask_rates) * len(args.mask_seeds)
    run_index = 0

    for mask_seed in args.mask_seeds:
        for mask_rate in args.mask_rates:
            run_index += 1
            masked = mask_training_relationships(
                train,
                mask_rate=mask_rate,
                seed=mask_seed,
            )
            masked_train = masked["records"]

            run_args = argparse.Namespace(
                dataset=args.dataset,
                dataset_path=str(dataset_path) if dataset_path else None,
                output_dir=None,
                checkpoint_dir=None,
                test_fraction=args.test_fraction,
                seed=args.split_seed,
                top_k=args.top_k,
                max_hops=args.max_hops,
                cross_validation_folds=0,
                limit_cases=args.limit_cases,
                with_llm=False,
                max_llm_cases=0,
            )

            logger.info(
                "E7 run %d/%d | mask_rate=%.0f%% mask_seed=%d "
                "removed=%d/%d",
                run_index,
                total_runs,
                mask_rate * 100,
                mask_seed,
                masked["removed_relationships"],
                masked["total_relationships"],
            )

            result = benchmark.run(
                run_args,
                records_override=tuple(masked_train) + tuple(test),
                split_override=(tuple(masked_train), tuple(test)),
            )

            run_record = {
                "mask_rate": mask_rate,
                "mask_seed": mask_seed,
                "split_seed": args.split_seed,
                "masking": {
                    key: value
                    for key, value in masked.items()
                    if key != "records"
                },
                "method_summary": result["method_summary"],
                "cases": _compact_case_results(result["cases"]),
            }
            run_records.append(run_record)

            # Persist each completed condition immediately. A later failure
            # cannot erase already completed E7 conditions.
            with runs_path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(run_record, ensure_ascii=False) + "\n")
                handle.flush()

    aggregate = _aggregate_runs(run_records)
    payload = {
        "experiment": "E7",
        "title": "Robustness under controlled relationship-evidence masking",
        "created_at": datetime.now(UTC).isoformat(),
        "protocol": {
            "dataset": args.dataset,
            "dataset_path": str(dataset_path or benchmark.DATASET_PATHS[args.dataset]),
            "dataset_sha256": benchmark.hashlib.sha256(
                (dataset_path or benchmark.DATASET_PATHS[args.dataset]).read_bytes()
            ).hexdigest(),
            "dataset_records": len(original_records),
            "fixed_split_seed": args.split_seed,
            "test_fraction": args.test_fraction,
            "train_scenarios": len(train),
            "test_scenarios": len(test),
            "train_scenario_ids": sorted(record.scenario_id for record in train),
            "test_scenario_ids": sorted(record.scenario_id for record in test),
            "test_queries": len(benchmark.make_cases(test)),
            "training_relationships_before_masking": original_training_edges,
            "mask_rates": list(args.mask_rates),
            "mask_seeds": list(args.mask_seeds),
            "masking_unit": "typed CausalRelation objects in training records",
            "masking_strategy": (
                "Global random edge masking without replacement; for each seed, "
                "the shuffled edge order is shared across rates, making masks nested."
            ),
            "mask_projection": (
                "Cause/effect/consequence endpoint fields used by TF-IDF are "
                "reconstructed from retained typed relationships."
            ),
            "test_labels_modified": False,
            "llm_enabled": False,
            "methods": [
                "tfidf_vector_retrieval",
                "graph_reasoning",
                "graph_tfidf_union",
            ],
            "limitations": [
                "Labels remain row-derived silver associations, not expert-validated causal ground truth.",
                "Masking is performed on typed relationships generated by the current CSV loader; it simulates evidence loss, not naturally occurring missingness.",
                "A single fixed scenario split isolates masking sensitivity but does not replace E6 split robustness.",
            ],
        },
        "aggregate": aggregate,
        "run_count": len(run_records),
        "runs_jsonl": str(runs_path),
        "summary_json": str(summary_path),
    }

    summary_path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    logger.info("E7 complete | summary=%s runs=%s", summary_path, runs_path)
    return payload


def _parse_csv_floats(value: str, option_name: str) -> tuple[float, ...]:
    try:
        values = tuple(float(part.strip()) for part in value.split(",") if part.strip())
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            f"{option_name} must be comma-separated numbers"
        ) from exc
    if not values:
        raise argparse.ArgumentTypeError(f"{option_name} cannot be empty")
    return values


def _parse_csv_ints(value: str, option_name: str) -> tuple[int, ...]:
    try:
        values = tuple(int(part.strip()) for part in value.split(",") if part.strip())
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            f"{option_name} must be comma-separated integers"
        ) from exc
    if not values:
        raise argparse.ArgumentTypeError(f"{option_name} cannot be empty")
    return values


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset",
        choices=sorted(benchmark.DATASET_PATHS),
        default="t301-reconstructed",
    )
    parser.add_argument("--dataset-path", default=None)
    parser.add_argument("--output-dir", default="results/e7")
    parser.add_argument("--test-fraction", type=float, default=0.2)
    parser.add_argument("--split-seed", type=int, default=42)
    parser.add_argument(
        "--mask-rates",
        type=lambda value: _parse_csv_floats(value, "--mask-rates"),
        default=DEFAULT_MASK_RATES,
        help="Comma-separated relationship masking fractions (default: 0.1,0.2,0.3,0.4).",
    )
    parser.add_argument(
        "--mask-seeds",
        type=lambda value: _parse_csv_ints(value, "--mask-seeds"),
        default=DEFAULT_MASK_SEEDS,
        help="Comma-separated random masking seeds (default: 42 through 51).",
    )
    parser.add_argument("--top-k", type=int, default=10)
    parser.add_argument("--max-hops", type=int, default=4)
    parser.add_argument("--limit-cases", type=int, default=None)
    args = parser.parse_args()

    if not 0.0 < args.test_fraction < 1.0:
        parser.error("--test-fraction must be between 0 and 1")
    if any(not 0.0 <= rate < 1.0 for rate in args.mask_rates):
        parser.error("--mask-rates values must be in [0, 1)")
    if any(seed < 0 for seed in args.mask_seeds):
        parser.error("--mask-seeds values must be >= 0")
    if args.top_k < 1:
        parser.error("--top-k must be >= 1")
    if args.max_hops < 2:
        parser.error("--max-hops must be >= 2")
    if args.limit_cases is not None and args.limit_cases < 1:
        parser.error("--limit-cases must be >= 1")
    return args


def main() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )
    args = parse_args()
    payload = run_experiment(args)
    print(json.dumps(payload["aggregate"], indent=2))
    print(f"\nE7 summary: {payload['runs_jsonl']}")
    print(f"E7 aggregate: results/e7 JSON summary written to {args.output_dir}")


if __name__ == "__main__":
    main()
