"""Sparse TF-IDF retrieval over structured HAZOP scenario records."""

from __future__ import annotations

import math
import re
import time
from collections import Counter
from collections.abc import Iterable

from app.application.strategies.retrieval.models import (
    RetrievalRequest,
    RetrievalResult,
    RetrievedEvidence,
    RetrievalScope,
)
from app.domain.entities.hazop_record import (
    CausalRelation,
    HazopRecord,
    RelationshipOrigin,
)
from app.domain.repositories.graph_repository import GraphRepository


_TOKEN_RE = re.compile(r"[a-z0-9]+")
_STOP_WORDS = frozenset(
    {
        "a", "an", "and", "are", "as", "at", "be", "by", "for",
        "from", "in", "is", "it", "of", "on", "or", "the", "to",
        "with", "due", "possible", "potential",
    }
)


def _tokens(text: str) -> list[str]:
    return [
        token
        for token in _TOKEN_RE.findall(text.casefold())
        if len(token) > 1 and token not in _STOP_WORDS
    ]


def _cosine(
    left: dict[str, float],
    right: dict[str, float],
) -> float:
    if not left or not right:
        return 0.0
    dot = sum(value * right.get(term, 0.0) for term, value in left.items())
    left_norm = math.sqrt(sum(value * value for value in left.values()))
    right_norm = math.sqrt(sum(value * value for value in right.values()))
    if left_norm == 0.0 or right_norm == 0.0:
        return 0.0
    return dot / (left_norm * right_norm)


def _scenario_context(record: HazopRecord) -> str:
    return " | ".join(
        value
        for value in (
            record.plant_unit,
            record.equipment,
            record.design_intent,
            record.parameter,
            record.guideword,
            record.deviation,
        )
        if value
    )


def _record_text(record: HazopRecord) -> str:
    parts = [
        record.plant_unit,
        record.equipment,
        record.design_intent,
        record.parameter,
        record.guideword,
        record.deviation,
        *record.causes,
        *record.consequences,
        *record.safeguards,
        *record.recommendations,
    ]
    return " ".join(parts)


def _origin(record: HazopRecord) -> RelationshipOrigin:
    if record.causal_relations:
        return record.causal_relations[0].origin
    return RelationshipOrigin.SYNTHETIC


class TfidfRetriever:
    """Retrieve row-associated cause/consequence candidates using TF-IDF.

    The returned relation is marked RETRIEVAL_INFERRED. It is generated by
    pairing fields co-listed in a HAZOP row and is not represented as a
    direct source-verified causal proposition.
    """

    def __init__(
        self,
        repository: GraphRepository,
        *,
        min_score: float = 0.05,
        max_records: int = 10_000,
    ) -> None:
        if not 0.0 <= min_score <= 1.0:
            raise ValueError("min_score must be between 0 and 1")
        if isinstance(max_records, bool) or max_records < 1:
            raise ValueError("max_records must be positive")
        self._repository = repository
        self._min_score = min_score
        self._max_records = max_records
        self._records: tuple[HazopRecord, ...] = ()
        self._idf: dict[str, float] = {}
        self._document_vectors: tuple[dict[str, float], ...] = ()
        self.index_build_ms = 0.0
        self.refresh()

    def refresh(self) -> None:
        """Rebuild the corpus index after records are added or updated."""

        started = time.perf_counter()
        records = tuple(
            self._repository.find_records(limit=self._max_records)
        )
        documents = [_tokens(_record_text(record)) for record in records]
        document_frequency: Counter[str] = Counter()
        for terms in documents:
            document_frequency.update(set(terms))

        count = len(documents)
        idf = {
            term: math.log((count + 1) / (frequency + 1)) + 1.0
            for term, frequency in document_frequency.items()
        }
        self._records = records
        self._idf = idf
        self._document_vectors = tuple(
            self._vector(terms, idf) for terms in documents
        )
        self.index_build_ms = (time.perf_counter() - started) * 1000.0

    def retrieve(self, request: RetrievalRequest) -> RetrievalResult:
        target = self._repository.get_record(request.scenario_id)
        if target is None:
            return RetrievalResult(
                scenario_id=request.scenario_id,
                scope=RetrievalScope.SCENARIO_LOCAL,
                evidence=(),
                scenario_exists=False,
            )

        if not self._records:
            return RetrievalResult(
                scenario_id=request.scenario_id,
                scope=RetrievalScope.SCENARIO_LOCAL,
                evidence=(),
                scenario_exists=True,
                scenario_context=_scenario_context(target),
            )

        records = self._records
        idf = self._idf
        query_terms = _tokens(request.known_endpoint)
        query_vector = self._vector(query_terms, idf)
        if not query_vector:
            return RetrievalResult(
                scenario_id=request.scenario_id,
                scope=RetrievalScope.SCENARIO_LOCAL,
                evidence=(),
                scenario_exists=True,
                graph_context=self._local_graph(target),
                scenario_context=_scenario_context(target),
            )

        scored_records: list[tuple[float, HazopRecord]] = []
        for record, document_vector in zip(
            records,
            self._document_vectors,
        ):
            record_score = _cosine(query_vector, document_vector)
            if record_score > 0.0:
                scored_records.append((record_score, record))

        scored_records.sort(
            key=lambda item: (-item[0], item[1].scenario_id.casefold())
        )

        evidence: list[RetrievedEvidence] = []
        seen: set[tuple[str, str, str, str]] = set()
        for record_score, record in scored_records:
            anchors = (
                record.consequences
                if request.missing_endpoint == "subject"
                else record.causes
            )
            missing_values = (
                record.causes
                if request.missing_endpoint == "subject"
                else record.consequences
            )
            if not anchors or not missing_values:
                continue

            for anchor in anchors:
                anchor_terms = _tokens(anchor)
                anchor_vector = self._vector(anchor_terms, idf)
                anchor_score = _cosine(query_vector, anchor_vector)
                if anchor.strip().casefold() == request.known_endpoint.strip().casefold():
                    anchor_score = 1.0

                # Anchor similarity is mandatory; a match on equipment or
                # deviation metadata alone must not return unrelated cause/
                # consequence pairs from the same row.
                if anchor_score < self._min_score:
                    continue
                score = 0.75 * anchor_score + 0.25 * record_score
                if score < self._min_score:
                    continue

                for missing_value in missing_values:
                    if request.missing_endpoint == "object":
                        # Reframe the retrieved analogue as a candidate for
                        # the exact query endpoint; preserve the matched
                        # training anchor in the evidence text below.
                        subject, object_ = request.known_endpoint, missing_value
                    else:
                        subject, object_ = missing_value, request.known_endpoint

                    key = (
                        record.scenario_id.casefold(),
                        subject.casefold(),
                        request.predicate.casefold(),
                        object_.casefold(),
                    )
                    if key in seen:
                        continue
                    seen.add(key)

                    row_origin = _origin(record)
                    provenance = (
                        record.source.provenance_note
                        if record.source is not None
                        else record.remarks
                    )
                    relation = CausalRelation(
                        subject=subject,
                        predicate=request.predicate,
                        object=object_,
                        origin=RelationshipOrigin.RETRIEVAL_INFERRED,
                        evidence=(
                            f"TF-IDF row candidate from scenario "
                            f"{record.scenario_id}; the source row lists "
                            f"retrieved anchor {anchor!r} and candidate "
                            f"endpoint {missing_value!r} in its cause/"
                            f"consequence fields. The query endpoint was "
                            f"{request.known_endpoint!r}. Underlying row origin: "
                            f"{row_origin.value}. This is co-occurrence-based "
                            f"retrieval, not a directly documented causal "
                            f"edge. Provenance: {provenance}"
                        ),
                        source_id=(
                            f"{record.source.document_id}:"
                            f"{record.scenario_id}"
                            if record.source is not None
                            else record.scenario_id
                        ),
                    )
                    evidence.append(
                        RetrievedEvidence(
                            scenario_id=record.scenario_id,
                            relation=relation,
                            scope=(
                                RetrievalScope.SCENARIO_LOCAL
                                if record.scenario_id == request.scenario_id
                                else RetrievalScope.CROSS_SCENARIO
                            ),
                            relevance_score=score,
                        )
                    )

            if len(evidence) >= request.limit:
                break

        evidence.sort(
            key=lambda item: (
                -(item.relevance_score or 0.0),
                item.scenario_id.casefold(),
                item.relation.object.casefold(),
            )
        )
        evidence = evidence[: request.limit]

        scopes = {item.scope for item in evidence}
        scope = (
            RetrievalScope.HYBRID
            if len(scopes) > 1
            else next(iter(scopes), RetrievalScope.SCENARIO_LOCAL)
        )
        return RetrievalResult(
            scenario_id=request.scenario_id,
            scope=scope,
            evidence=tuple(evidence),
            scenario_exists=True,
            graph_context=self._local_graph(target),
            scenario_context=_scenario_context(target),
        )

    @staticmethod
    def _vector(
        terms: Iterable[str],
        idf: dict[str, float],
    ) -> dict[str, float]:
        frequencies = Counter(terms)
        return {
            term: (1.0 + math.log(frequency)) * idf[term]
            for term, frequency in frequencies.items()
            if term in idf
        }

    @staticmethod
    def _local_graph(record) -> tuple[RetrievedEvidence, ...]:
        return tuple(
            RetrievedEvidence(
                scenario_id=record.scenario_id,
                relation=relation,
                scope=RetrievalScope.SCENARIO_LOCAL,
            )
            for relation in record.causal_relations
            if relation.origin not in {
                RelationshipOrigin.MODEL_INFERRED,
                RelationshipOrigin.RETRIEVAL_INFERRED,
                RelationshipOrigin.GRAPH_INFERRED,
            }
        )
